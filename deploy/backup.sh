#!/usr/bin/env bash
# Daily database backup to external storage (restic). Runs from a systemd timer
# (deploy/systemd/sensoterra-backup.timer), or by hand from the app directory:
#   ./deploy/backup.sh                 # dump -> verify -> restic backup -> forget/prune -> check
#   ./deploy/backup.sh init            # once: create the restic repository
#   ./deploy/backup.sh restic <args>   # any restic command, e.g. snapshots, stats, unlock
#
# Settings live in .env.backup next to .env (chmod 600), template: deploy/env.backup.example.
# restic runs in a container, nothing to install on the host.
# The repository gets the dump (pg_dump -Fc) and .env: a restored database is useless without
# its secrets. The repository is encrypted with RESTIC_PASSWORD — keep it OFF the VPS.
set -euo pipefail
# Dumps contain password hashes, device keys and invite tokens: owner-only files.
umask 077

cd "$(dirname "$0")/.."
[ -f .env ] || { echo "ERROR: .env not found in $(pwd)" >&2; exit 1; }
[ -f .env.backup ] || { echo "ERROR: .env.backup not found in $(pwd), see deploy/env.backup.example" >&2; exit 1; }

# shellcheck source=deploy/restic-lib.sh
. deploy/restic-lib.sh

KEEP_LOCAL="$(backup_value KEEP_LOCAL_DUMPS)"; KEEP_LOCAL="${KEEP_LOCAL:-3}"
KEEP_DAILY="$(backup_value RESTIC_KEEP_DAILY)"; KEEP_DAILY="${KEEP_DAILY:-7}"
KEEP_WEEKLY="$(backup_value RESTIC_KEEP_WEEKLY)"; KEEP_WEEKLY="${KEEP_WEEKLY:-4}"
KEEP_MONTHLY="$(backup_value RESTIC_KEEP_MONTHLY)"; KEEP_MONTHLY="${KEEP_MONTHLY:-12}"
HEALTHCHECK_URL="$(backup_value HEALTHCHECK_URL)"

log() { echo "[backup] $*"; }

case "${1:-}" in
    init)
        restic init
        exit 0
        ;;
    restic)
        shift
        restic "$@"
        exit 0
        ;;
    "") ;;
    *)
        echo "usage: $0 [init | restic <args>]" >&2
        exit 2
        ;;
esac

# Monitoring ping (healthchecks.io and compatible): /start, success, /fail.
# Skipped without HEALTHCHECK_URL; a failed ping does not fail the backup.
ping_hc() {
    [ -n "$HEALTHCHECK_URL" ] || return 0
    curl -fsS -m 10 --retry 3 -o /dev/null "${HEALTHCHECK_URL}$1" || log "WARN: healthcheck ping failed"
}
trap '[ $? -eq 0 ] || ping_hc /fail' EXIT
ping_hc /start

# ---------- dump ----------
mkdir -p backups/daily
DUMP="backups/daily/sensoterra-$(date +%Y%m%d-%H%M%S).dump"
log "pg_dump -> $DUMP"
# -Z0: no pg_dump compression — restic compresses and deduplicates itself, while a compressed
# dump would be a new set of bytes every day and take its full size in the storage.
# shellcheck disable=SC2016 # variables expand inside the DB container
compose exec -T timescaledb sh -c 'pg_dump -Fc -Z0 -U "$POSTGRES_USER" "$POSTGRES_DB"' > "$DUMP.tmp"

# The dump must be readable: its table of contents parses and lists the app tables.
TOC="$(compose exec -T timescaledb pg_restore --list < "$DUMP.tmp")"
if ! grep -q ' TABLE public app_user ' <<<"$TOC"; then
    rm -f "$DUMP.tmp"
    log "ERROR: dump has no app_user table — refusing to upload it"
    exit 1
fi
mv "$DUMP.tmp" "$DUMP"
log "dump OK: $(du -h "$DUMP" | cut -f1), $(grep -c ' TABLE DATA ' <<<"$TOC") tables with data"

# ---------- restic ----------
log "restic backup"
restic_with_dump "$DUMP" backup /backup --tag daily

log "restic forget --prune (daily $KEEP_DAILY, weekly $KEEP_WEEKLY, monthly $KEEP_MONTHLY)"
restic forget --prune --tag daily \
    --keep-daily "$KEEP_DAILY" --keep-weekly "$KEEP_WEEKLY" --keep-monthly "$KEEP_MONTHLY"

# Repository structure integrity; the data itself is read monthly by restore.sh check.
log "restic check"
restic check

# Keep the last few dumps locally for a quick restore without downloading.
# shellcheck disable=SC2012 # dump names are generated by this script
ls -1t backups/daily/sensoterra-*.dump | tail -n +"$((KEEP_LOCAL + 1))" | xargs -r rm --

ping_hc ""
log "OK"
